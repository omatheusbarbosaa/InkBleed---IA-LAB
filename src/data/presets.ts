export function randomizeStudioParams(
  current: StudioParams,
  mode: 'light' | 'aggressive'
): StudioParams {
  if (mode === 'light') {
    return {
      ...current,
      seed: Math.round(Math.random() * 10000) / 100,
      inkbleedAmount: perturb(current.inkbleedAmount, 18, 12, 72),
      inkbleedCapillarity: perturb(current.inkbleedCapillarity, 20, 15, 80),
      inkbleedWash: perturb(current.inkbleedWash, 18, 8, 65),
      inkbleedStipple: perturb(current.inkbleedStipple, 18, 5, 70),
      inkbleedPooling: perturb(current.inkbleedPooling, 16, 10, 65),
      inkbleedNoiseThreshold: perturb(current.inkbleedNoiseThreshold, 18, 8, 72),

      xeroxGrain: perturb(current.xeroxGrain, 16, 10, 68),
      xeroxStreaks: perturb(current.xeroxStreaks, 16, 0, 55),
      xeroxDust: perturb(current.xeroxDust, 14, 5, 50),
      xeroxContrast: perturb(current.xeroxContrast, 16, 15, 68),
      paperTooth: perturb(current.paperTooth, 16, 15, 75),

      distressErosion: perturb(current.distressErosion, 14, 5, 52),
      distressDryBrush: perturb(current.distressDryBrush, 14, 0, 45),
      distressJitter: perturb(current.distressJitter, 10, 0, 32),

      halftoneAmount: perturb(current.halftoneAmount, 22, 0, 75),
      halftoneScale: perturb(current.halftoneScale, 6, 6, 36),
      halftoneAngle: (current.halftoneAngle + Math.round(randRange(-15, 15)) + 90) % 90,

      motionBlurAmount: perturb(current.motionBlurAmount, 18, 0, 56),
      motionBlurAngle: (current.motionBlurAngle + Math.round(randRange(-35, 35)) + 360) % 360,
      motionSpatialGradient: perturb(current.motionSpatialGradient, 20, 0, 70),
      motionShearBand: perturb(current.motionShearBand, 18, 0, 48),
      motionEcho: perturb(current.motionEcho, 14, 0, 40),
    };
  }

  // Aggressive randomization: wild experimental generative compositions
  const randomFont =
    CURATED_GOOGLE_FONTS[Math.floor(Math.random() * CURATED_GOOGLE_FONTS.length)];
  const palette =
    AGGRESSIVE_PALETTES[Math.floor(Math.random() * AGGRESSIVE_PALETTES.length)];
  const scanOverlays: StudioParams['scanOverlay'][] = [
    'none',
    'none',
    'xerox-dark',
    'xerox-light',
    'halftone-ref',
  ];
  const chosenOverlay =
    scanOverlays[Math.floor(Math.random() * scanOverlays.length)];

  const useShear = Math.random() > 0.35;
  const useHalftone = Math.random() > 0.25;

  const useGradientMap = Math.random() > 0.62;
  const gmPreset =
    GRADIENT_MAP_PRESETS[Math.floor(Math.random() * GRADIENT_MAP_PRESETS.length)];

  return {
    ...current,
    seed: Math.round(Math.random() * 10000) / 100,
    paperColor: palette.paper,
    inkColor: palette.ink,
    textColor: palette.invert ? palette.paper : palette.ink,
    invertOutput: palette.invert,

    gradientMapEnabled: useGradientMap,
    gradientMapShadow: gmPreset.shadow,
    gradientMapMidEnabled: gmPreset.midEnabled,
    gradientMapMid: gmPreset.mid,
    gradientMapMidPos: gmPreset.midPos,
    gradientMapHighlight: gmPreset.highlight,
    gradientMapOpacity: useGradientMap ? Math.round(randRange(70, 100)) : current.gradientMapOpacity,
    gradientMapReverse: useGradientMap ? Math.random() > 0.78 : current.gradientMapReverse,

    fontFamily: randomFont.family,
    fontWeight:
      randomFont.weights[Math.floor(Math.random() * randomFont.weights.length)] ?? 700,
    letterSpacing: Math.round(randRange(-0.07, 0.08) * 100) / 100,
    textRotation: Math.random() > 0.65 ? Math.round(randRange(-10, 10)) : 0,

    inkbleedAmount: Math.round(randRange(28, 92)),
    inkbleedCapillarity: Math.round(randRange(35, 95)),
    inkbleedWash: Math.round(randRange(18, 85)),
    inkbleedStipple: Math.round(randRange(15, 95)),
    inkbleedPooling: Math.round(randRange(20, 88)),
    inkbleedNoiseThreshold: Math.round(randRange(18, 95)),

    xeroxGrain: Math.round(randRange(28, 92)),
    xeroxStreaks: Math.round(randRange(18, 90)),
    xeroxDust: Math.round(randRange(15, 82)),
    xeroxContrast: Math.round(randRange(30, 88)),
    paperTooth: Math.round(randRange(20, 85)),
    scanOverlay: chosenOverlay,
    scanOverlayOpacity: Math.round(randRange(25, 68)),

    distressErosion: Math.round(randRange(18, 78)),
    distressDryBrush: Math.round(randRange(10, 68)),
    distressJitter: Math.round(randRange(8, 55)),

    halftoneAmount: useHalftone ? Math.round(randRange(25, 95)) : 0,
    halftoneScale: Math.round(randRange(7, 36)),
    halftoneAngle: Math.round(randRange(0, 90)),

    motionBlurAmount: Math.round(randRange(20, 92)),
    motionBlurAngle: Math.round(randRange(0, 360)),
    motionSpatialGradient: Math.round(randRange(10, 95)),
    motionShearBand: useShear ? Math.round(randRange(32, 92)) : 0,
    motionShearPos: Math.round(randRange(22, 78)),
    motionEcho: Math.round(randRange(10, 75)),
  };
}
